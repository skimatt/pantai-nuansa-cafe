import { chromium } from '@playwright/test';
import { mkdir,writeFile } from 'node:fs/promises';
const browser=await chromium.launch(),reports=[];
const base=process.env.NUANSA_PREVIEW_URL??'http://127.0.0.1:4173';
await mkdir('evidence/screenshots/final',{recursive:true});
for(const reducedMotion of ['no-preference','reduce']){
 const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,reducedMotion});
 const page=await context.newPage(),cdp=await context.newCDPSession(page),requests=[],requestUrls=new Map();
 let videoBytes=0;
 await cdp.send('Network.enable');await cdp.send('Network.setCacheDisabled',{cacheDisabled:true});
 await cdp.send('Emulation.setCPUThrottlingRate',{rate:4});
 await cdp.send('Network.emulateNetworkConditions',{offline:false,latency:150,downloadThroughput:200000,uploadThroughput:90000});
 cdp.on('Network.requestWillBeSent',e=>requestUrls.set(e.requestId,e.request.url));
 cdp.on('Network.dataReceived',e=>{if(requestUrls.get(e.requestId)?.endsWith('.mp4'))videoBytes+=e.encodedDataLength;});
 page.on('request',r=>requests.push(r.url()));
 await page.addInitScript(()=>{
  window.__journeyPerf={lcp:0,cls:0,longTasks:[]};
  new PerformanceObserver(list=>{for(const e of list.getEntries())window.__journeyPerf.lcp=e.startTime;}).observe({type:'largest-contentful-paint',buffered:true});
  new PerformanceObserver(list=>{for(const e of list.getEntries())if(!e.hadRecentInput)window.__journeyPerf.cls+=e.value;}).observe({type:'layout-shift',buffered:true});
  new PerformanceObserver(list=>{for(const e of list.getEntries())window.__journeyPerf.longTasks.push(e.duration);}).observe({type:'longtask',buffered:true});
 });
 await page.goto(base);
 await page.waitForFunction(()=>document.querySelector('.arrival')?.getAttribute('data-intro')==='hero',{},{timeout:40000});
 const hero=await page.evaluate(()=>({...window.__journeyPerf,resourceBytes:performance.getEntriesByType('resource').reduce((s,e)=>s+e.transferSize,0)}));
 await page.locator('#discover').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
 await page.locator('.documentary-photo img').evaluateAll(async imgs=>Promise.all(imgs.map(img=>img.decode())));
 await page.locator('.documentary-player').scrollIntoViewIfNeeded();
 await page.locator('.documentary-poster').evaluate(img=>img.decode());
 const videoRequestsBeforePlay=requests.filter(url=>url.endsWith('.mp4')).length;
 const start=await page.evaluate(()=>performance.now());
 await page.getByRole('button',{name:'Putar video senja',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.1,{},{timeout:40000});
 const firstFrameObservedMs=await page.evaluate(()=>performance.now())-start;
 await page.getByRole('button',{name:'Jeda video senja'}).click();
 await page.locator('#taste').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
 await page.getByRole('button',{name:/Nasi Goreng Seafood/}).click();
 await page.locator('#taste-selected-media img').evaluate(image=>image.decode());
 await page.locator('#moments').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
 await page.locator('.moment-open').first().click();
 await page.locator('.gallery-viewer img').evaluate(image=>image.decode());
 await page.getByRole('button',{name:'Tutup dokumentasi'}).click();
 await page.locator('#find-us').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
 const final=await page.evaluate(()=>({...window.__journeyPerf,resourceBytes:performance.getEntriesByType('resource').reduce((s,e)=>s+e.transferSize,0),heapBytes:performance.memory?.usedJSHeapSize??null}));
 await page.screenshot({path:`evidence/screenshots/final/performance-${reducedMotion}.png`});
 reports.push({date:'2026-11-03',browser:browser.version(),viewport:'390×844',cpuSlowdown:4,latencyMs:150,downloadBytesPerSecond:200000,reducedMotion,heroLcpMs:hero.lcp,heroCls:hero.cls,heroResourceBytes:hero.resourceBytes,journeyCls:final.cls,completedResourceBytes:final.resourceBytes,videoRequestsBeforePlay,videoRequestsAfterPlay:requests.filter(url=>url.endsWith('.mp4')).length,videoBytesObservedViaCDP:videoBytes,firstFrameObservedMs,longTaskCount:final.longTasks.length,maxLongTaskMs:Math.max(0,...final.longTasks),heapBytes:final.heapBytes,limitations:'Single local Chromium CDP simulation, run without e2e concurrently; not physical mid-range-device results, field INP or a controlled benchmark. HTTP is uncompressed. First-frame timing includes Playwright click/visibility overhead. Completed resource transfer sizes omit unfinished video requests; CDP byte counter is a partial observed sample.'});
 await context.close();
}
await mkdir('evidence/performance',{recursive:true});await writeFile('evidence/performance/full-site-mobile-baseline.json',JSON.stringify(reports,null,2));
await browser.close();console.log(JSON.stringify(reports,null,2));
if(reports.some(r=>r.videoRequestsBeforePlay>0))process.exitCode=1;
