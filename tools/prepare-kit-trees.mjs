import sharp from 'sharp';
import {execFileSync} from 'node:child_process';
import {copyFile,readFile,writeFile} from 'node:fs/promises';
const root='deliverables/coastal-asset-kit';
const original='assets-source/generated/coastal-tree-sheet-v1.png';
await copyFile(original,`${root}/source/coastal-tree-sheet-v1.png`);
const {data,info}=await sharp(original).ensureAlpha().raw().toBuffer({resolveWithObject:true});
function gap(y,lo,hi,target){let best=Infinity,at=target;for(let x=lo;x<=hi;x++){let score=0;for(let k=-4;k<=4;k++)score+=data[(y*info.width+x+k)*4+3];score+=Math.abs(x-target)*.01;if(score<best){best=score;at=x;}}return at;}
const masked=Array.from({length:3},()=>Buffer.alloc(data.length));
for(let y=0;y<info.height;y++){
 const a=gap(y,360,560,490),b=gap(y,900,1100,990);
 for(let x=0;x<info.width;x++){
  const i=(y*info.width+x)*4,index=x<a?0:x<b?1:2;
  data.copy(masked[index],i,i,i+4);
  masked[index][i+3]=Math.max(0,Math.round((data[i+3]-24)*255/231));
 }
}
const manifest=JSON.parse(await readFile(`${root}/manifest.json`,'utf8'));
for(const [index,id]of ['tree-coastal-pine','tree-almond','tree-banyan'].entries()){
 const cropped=await sharp(masked[index],{raw:{width:info.width,height:info.height,channels:4}}).trim({threshold:0}).extend({top:12,bottom:12,left:12,right:12,background:'#00000000'}).png().toBuffer();
 const meta=await sharp(cropped).metadata();await writeFile(`${root}/png/${id}.png`,cropped);
 await sharp(cropped).resize({height:720,withoutEnlargement:true}).webp({quality:88}).toFile(`${root}/webp/${id}.webp`);
 const e=manifest.assets.find(e=>e.id===id);e.sourceType='generated';e.rasterProvenance='source/coastal-tree-sheet-v1.png';e.note='Painterly raster generated by built-in imagegen; SVG and GLB are independent procedural structural models, not sources of this raster.';e.width=meta.width;e.height=meta.height;
}
execFileSync('python',['tools/clean-kit-alpha.py']);
for(const id of ['tree-coastal-pine','tree-almond','tree-banyan'])await sharp(`${root}/png/${id}.png`).resize({height:720,withoutEnlargement:true}).webp({quality:88}).toFile(`${root}/webp/${id}.webp`);
await writeFile(`${root}/manifest.json`,JSON.stringify(manifest,null,2));console.log('Separated three transparent painterly trees along alpha gutters; originals preserved.');
